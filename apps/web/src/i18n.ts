/**
 * Minimal i18n: Spanish is the source language (the product is for buyers in
 * Mexico) and English is a translation layer for international demos.
 * Keys are the Spanish strings; `{name}` placeholders are interpolated.
 * Data coming from the database (product names, seeded purposes) goes through
 * `t()` too: unknown strings fall back to themselves.
 */
export type Lang = 'es' | 'en';

function initialLang(): Lang {
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q === 'es' || q === 'en') { localStorage.setItem('lang', q); return q; }
    const saved = localStorage.getItem('lang');
    if (saved === 'es' || saved === 'en') return saved;
  } catch { /* storage unavailable: use default */ }
  return 'en';
}

export const lang: Lang = initialLang();
export const locale = lang === 'en' ? 'en-US' : 'es-MX';

export function setLang(l: Lang) {
  try { localStorage.setItem('lang', l); } catch { /* ignore */ }
  const url = new URL(window.location.href);
  url.searchParams.delete('lang');
  window.location.replace(url.toString());
}

export function t(s: string, vars?: Record<string, string | number>): string {
  let out = lang === 'en' ? EN[s] ?? s : s;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

